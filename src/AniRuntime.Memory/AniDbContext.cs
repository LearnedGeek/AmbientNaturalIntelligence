    public DbSet<DesireStateEntity>         DesireState         { get; set; } = null!;
    public DbSet<EmotionalStateBlobEntity>  EmotionalState      { get; set; } = null!;
    public DbSet<RelationshipHealthEntity>  RelationshipHealth  { get; set; } = null!;

    // ── Time-series + analytics ────────────────────────────────────────
    public DbSet<EmotionalStateHistoryEntity>  EmotionalStateHistory { get; set; } = null!;
    public DbSet<EmotionalContributionEntity>  EmotionalContributions { get; set; } = null!;
